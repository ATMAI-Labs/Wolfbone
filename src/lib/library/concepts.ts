import type { AreaId, Concept } from './types';

/** Original editorial explanations. Links describe this explanation, not formal proof dependencies. */
type Links = {
  uses?: string[];
  related?: string[];
  specializes?: string[];
  modules?: string[];
  playgroundId?: string;
};
function entry(
  id: string,
  name: string,
  symbol: string,
  kind: Concept['kind'],
  summary: string,
  detail: string,
  example: string,
  context: string,
  links: Links = {},
): Omit<Concept, 'area'> {
  return {
    id,
    name,
    symbol,
    kind,
    summary,
    detail,
    example,
    context,
    uses: links.uses ?? [],
    related: links.related ?? [],
    sourceModules: (links.modules ?? []).map((module) => `Mathlib.${module}`),
    ...(links.specializes ? { specializes: links.specializes } : {}),
    ...(links.playgroundId ? { playgroundId: links.playgroundId } : {}),
  };
}
function area(id: AreaId, entries: Omit<Concept, 'area'>[]): Concept[] {
  return entries.map((concept) => ({ ...concept, area: id }));
}

